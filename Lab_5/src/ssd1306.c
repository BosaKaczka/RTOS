// ---------------------------------------------------------------------------
// Internal helper: send a single command byte to the display
// ---------------------------------------------------------------------------
static void ssd1306_cmd(i2c_inst_t *i2c, uint8_t cmd)
{
    uint8_t buf[2] = {0x00, cmd}; // 0x00 = Co=0, D/C#=0 (command)
    i2c_write_blocking(i2c, SSD1306_ADDR, buf, 2, false);
}

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

void ssd1306_init(ssd1306_t *disp, i2c_inst_t *i2c)
{
    memset(disp->buf, 0, SSD1306_BUF_LEN);

    // Initialisation sequence for SSD1306 128x32
    ssd1306_cmd(i2c, SSD1306_DISPLAY_OFF);
    ssd1306_cmd(i2c, SSD1306_SET_DISPLAY_CLOCK);  ssd1306_cmd(i2c, 0x80);
    ssd1306_cmd(i2c, SSD1306_SET_MULTIPLEX);       ssd1306_cmd(i2c, 0x1F); // 32-1
    ssd1306_cmd(i2c, SSD1306_SET_DISPLAY_OFFSET);  ssd1306_cmd(i2c, 0x00);
    ssd1306_cmd(i2c, SSD1306_SET_START_LINE | 0x00);
    ssd1306_cmd(i2c, SSD1306_CHARGE_PUMP);         ssd1306_cmd(i2c, 0x14); // enable
    ssd1306_cmd(i2c, SSD1306_MEMORY_MODE);         ssd1306_cmd(i2c, 0x00); // horizontal
    ssd1306_cmd(i2c, SSD1306_SEG_REMAP);           // col 127 -> SEG0
    ssd1306_cmd(i2c, SSD1306_COM_SCAN_DEC);
    ssd1306_cmd(i2c, SSD1306_SET_COM_PINS);        ssd1306_cmd(i2c, 0x02); // 32-row
    ssd1306_cmd(i2c, SSD1306_SET_CONTRAST);        ssd1306_cmd(i2c, 0x8F);
    ssd1306_cmd(i2c, SSD1306_SET_PRECHARGE);       ssd1306_cmd(i2c, 0xF1);
    ssd1306_cmd(i2c, SSD1306_SET_VCOM_DETECT);     ssd1306_cmd(i2c, 0x40);
    ssd1306_cmd(i2c, SSD1306_DISPLAY_ALL_ON_RESUME);
    ssd1306_cmd(i2c, SSD1306_NORMAL_DISPLAY);
    ssd1306_cmd(i2c, SSD1306_DISPLAY_ON);
}

void ssd1306_send_frame(ssd1306_t *disp, i2c_inst_t *i2c)
{
    // Set column and page address window to full display
    ssd1306_cmd(i2c, SSD1306_COLUMN_ADDR); ssd1306_cmd(i2c, 0); ssd1306_cmd(i2c, SSD1306_WIDTH - 1);
    ssd1306_cmd(i2c, SSD1306_PAGE_ADDR);   ssd1306_cmd(i2c, 0); ssd1306_cmd(i2c, 3); // 4 pages for 32px

    // Send frame buffer prefixed with data control byte
    uint8_t frame[SSD1306_BUF_LEN + 1];
    frame[0] = 0x40; // Co=0, D/C#=1 (data)
    memcpy(frame + 1, disp->buf, SSD1306_BUF_LEN);
    i2c_write_blocking(i2c, SSD1306_ADDR, frame, sizeof(frame), false);
}

void ssd1306_clear(ssd1306_t *disp)
{
    memset(disp->buf, 0, SSD1306_BUF_LEN);
}

void ssd1306_draw_pixel(ssd1306_t *disp, int x, int y, bool on)
{
    if (x < 0 || x >= SSD1306_WIDTH || y < 0 || y >= SSD1306_HEIGHT) return;
    int byte_idx = x + (y / 8) * SSD1306_WIDTH;
    uint8_t bit   = 1 << (y % 8);
    if (on)
        disp->buf[byte_idx] |=  bit;
    else
        disp->buf[byte_idx] &= ~bit;
}

void ssd1306_draw_char(ssd1306_t *disp, int x, int y, char c)
{
    if (c < 0x20 || c > 0x7E) c = '?';
    const uint8_t *glyph = font5x7[(uint8_t)(c - 0x20)];
    for (int col = 0; col < 5; col++) {
        uint8_t column = glyph[col];
        for (int row = 0; row < 7; row++) {
            ssd1306_draw_pixel(disp, x + col, y + row, (column >> row) & 1);
        }
    }
}

void ssd1306_draw_string(ssd1306_t *disp, int x, int y, const char *str)
{
    while (*str) {
        ssd1306_draw_char(disp, x, y, *str++);
        x += 6; // 5 pixels + 1 spacing
        if (x + 6 > SSD1306_WIDTH) break;
    }
}

void ssd1306_draw_line_h(ssd1306_t *disp, int x, int y, int len)
{
    for (int i = 0; i < len; i++)
        ssd1306_draw_pixel(disp, x + i, y, true);
}
